#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');
const { applyVerifiedTrailOverrides } = require('./verified-trail-overrides');

const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'data', 'regions');
const detailDir = path.join(root, 'data', 'trail-details');
const sourceFiles = [
  'trails-data.js', 'osm-trails-data.js', 'osm-trails-savoy-data.js',
  'regions-config.js', 'water-sources-all-regions.geojson', 'huts-bars-all-regions.geojson',
  'data/verified-trail-overrides.json',
];
fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(detailDir, { recursive: true });

function loadTrails() {
  const context = { window: {}, console };
  vm.createContext(context);
  ['trails-data.js', 'osm-trails-data.js', 'osm-trails-savoy-data.js', 'regions-config.js']
    .forEach(file => vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file }));
  const trails = JSON.parse(vm.runInContext('window.DoloPawsRegions.assign(trails); JSON.stringify(trails)', context));
  const overrides = JSON.parse(fs.readFileSync(path.join(root, 'data', 'verified-trail-overrides.json'), 'utf8'));
  return applyVerifiedTrailOverrides(trails, overrides);
}

function loadGondolas() {
  const context = { window: {}, console };
  vm.createContext(context);
  vm.runInContext(fs.readFileSync(path.join(root, 'trails-data.js'), 'utf8'), context, { filename: 'trails-data.js' });
  return JSON.parse(vm.runInContext('JSON.stringify(gondolas)', context));
}

function featurePoint(feature) {
  const geometry = feature && feature.geometry;
  if (!geometry) return null;
  if (geometry.type === 'Point') return geometry.coordinates;
  let ring = null;
  if (geometry.type === 'Polygon') ring = geometry.coordinates[0];
  if (geometry.type === 'MultiPolygon') ring = geometry.coordinates[0] && geometry.coordinates[0][0];
  if (!Array.isArray(ring) || !ring.length) return null;
  return [
    ring.reduce((sum, point) => sum + point[0], 0) / ring.length,
    ring.reduce((sum, point) => sum + point[1], 0) / ring.length,
  ];
}

// The two launch regions are geographically disjoint. This midpoint is well
// east of Savoy and west of the Dolomites, so it is deterministic and leaves
// no ambiguous production POI in either package.
function regionForFeature(feature) {
  const point = featurePoint(feature);
  return point && point[0] < 9 ? 'savoy' : 'dolomites';
}

function pointFeature(feature) {
  const point = featurePoint(feature);
  return point ? { ...feature, geometry: { type: 'Point', coordinates: point } } : null;
}

function writeJson(file, value) {
  fs.writeFileSync(path.join(outDir, file), JSON.stringify(value));
}

const trails = loadTrails();
const gondolas = loadGondolas();
const byRegion = {
  dolomites: trails.filter(trail => trail.region === 'dolomites'),
  savoy: trails.filter(trail => trail.region === 'savoy'),
};
const gondolasByRegion = {
  dolomites: gondolas.filter(lift => lift.from && lift.from.lng >= 9),
  savoy: gondolas.filter(lift => lift.from && lift.from.lng < 9),
};
const trailAssetVersions = {};
const detailAssetVersions = {};

function liftsNearTrail(trail, lifts) {
  const path = Array.isArray(trail.path) && trail.path.length
    ? trail.path
    : [[trail.lat, trail.lng]];
  const latitudes = path.map(point => point[0]).filter(Number.isFinite);
  const longitudes = path.map(point => point[1]).filter(Number.isFinite);
  if (!latitudes.length || !longitudes.length) return [];

  // Keep the immediately useful lift context without making a trail detail
  // download the entire regional catalogue. About 7 km is enough to explain
  // nearby lift access while remaining a very small payload.
  const padding = 0.065;
  const minLat = Math.min(...latitudes) - padding;
  const maxLat = Math.max(...latitudes) + padding;
  const minLng = Math.min(...longitudes) - padding;
  const maxLng = Math.max(...longitudes) + padding;
  return lifts.filter(lift => {
    const points = [lift.from, lift.to].filter(Boolean);
    return points.some(point => point.lat >= minLat && point.lat <= maxLat && point.lng >= minLng && point.lng <= maxLng);
  });
}

function detailPayload(trail, lifts) {
  const nearbyLifts = liftsNearTrail(trail, lifts);
  return `// Generated by scripts/build-regional-runtime-data.js. Do not edit.\n` +
    `(function(){var trail=${JSON.stringify(trail)};` +
    `var current=Array.isArray(window.trails)?window.trails:[];` +
    `window.trails=current.some(function(item){return item.id===trail.id;})?current:current.concat([trail]);` +
    `var incomingLifts=${JSON.stringify(nearbyLifts)};` +
    `var currentLifts=Array.isArray(window.gondolas)?window.gondolas:[];` +
    `var liftIds=new Set(currentLifts.map(function(lift){return lift.name+'|'+lift.from.lat+'|'+lift.from.lng;}));` +
    `window.gondolas=currentLifts.concat(incomingLifts.filter(function(lift){return !liftIds.has(lift.name+'|'+lift.from.lat+'|'+lift.from.lng);}));})();\n`;
}

for (const [region, regionTrails] of Object.entries(byRegion)) {
  const source = `// Generated by scripts/build-regional-runtime-data.js. Do not edit.\n` +
    `(function(){var incoming=${JSON.stringify(regionTrails)};` +
    `var current=Array.isArray(window.trails)?window.trails:[];` +
    `var ids=new Set(current.map(function(trail){return trail.id;}));` +
    `window.trails=current.concat(incoming.filter(function(trail){return !ids.has(trail.id);}));` +
    `var incomingLifts=${JSON.stringify(gondolasByRegion[region])};` +
    `var currentLifts=Array.isArray(window.gondolas)?window.gondolas:[];` +
    `var liftIds=new Set(currentLifts.map(function(lift){return lift.name+'|'+lift.from.lat+'|'+lift.from.lng;}));` +
    `window.gondolas=currentLifts.concat(incomingLifts.filter(function(lift){return !liftIds.has(lift.name+'|'+lift.from.lat+'|'+lift.from.lng);}));})();\n`;
  trailAssetVersions[region] = crypto.createHash('sha256').update(source).digest('hex').slice(0, 12);
  fs.writeFileSync(path.join(outDir, `${region}-trails.js`), source);
  detailAssetVersions[region] = Object.fromEntries(regionTrails.map(trail => {
    const source = detailPayload(trail, gondolasByRegion[region]);
    const version = crypto.createHash('sha256').update(source).digest('hex').slice(0, 12);
    fs.writeFileSync(path.join(detailDir, `${trail.id}.js`), source);
    return [trail.id, `data/trail-details/${trail.id}.js?v=${version}`];
  }));
}

const poiSources = {
  water: JSON.parse(fs.readFileSync(path.join(root, 'water-sources-all-regions.geojson'), 'utf8')),
  'huts-bars': JSON.parse(fs.readFileSync(path.join(root, 'huts-bars-all-regions.geojson'), 'utf8')),
};

for (const [kind, collection] of Object.entries(poiSources)) {
  for (const region of Object.keys(byRegion)) {
    writeJson(`${region}-${kind}.geojson`, {
      type: 'FeatureCollection',
      features: (collection.features || [])
        .filter(feature => regionForFeature(feature) === region)
        .map(pointFeature)
        .filter(Boolean),
    });
  }
}

const manifest = {
  schemaVersion: 1,
  generatedAt: new Date(Math.max(...sourceFiles.map(file => fs.statSync(path.join(root, file)).mtimeMs))).toISOString(),
  regions: {},
  trailRegion: {},
};

for (const [region, regionTrails] of Object.entries(byRegion)) {
  manifest.regions[region] = {
    trailCount: regionTrails.length,
    trails: `data/regions/${region}-trails.js?v=${trailAssetVersions[region]}`,
    details: detailAssetVersions[region],
    water: `data/regions/${region}-water.geojson`,
    hutsBars: `data/regions/${region}-huts-bars.geojson`,
    dogRoutes: region === 'savoy' ? 'dog-friendly-routes-savoy.geojson' : 'dog-friendly-routes.geojson',
    optional: [],
  };
  regionTrails.forEach(trail => { manifest.trailRegion[trail.id] = region; });
}

fs.writeFileSync(path.join(root, 'data', 'regions-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(
  path.join(root, 'regions-runtime-manifest.js'),
  `// Generated by scripts/build-regional-runtime-data.js. Do not edit.\nwindow.DoloPawsRegionManifest=${JSON.stringify(manifest)};\n`,
);

console.log(`Built ${byRegion.dolomites.length} Dolomites and ${byRegion.savoy.length} Savoy trails.`);
