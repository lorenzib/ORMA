// English addresses that have an Italian copy, as written in a page's links.
const ITALIAN_LINKS = [
  [/^(?:\/|\/?index\.html)$/, '/it/'],
  [/^\/?(browse-trails|about|how-scoring-works|contact|safety-guide|privacy|terms)\.html$/, '/it/$1.html'],
  [/^\/?(guides\/[\w-]+\.html)$/, '/it/$1'],
  [/^\/?(trails\/[\w-]+\.html)$/, '/it/$1'],
];

let dictionaries = null;
function italian(){
  if(!dictionaries){
    const slices = dictionarySlices(fs.readFileSync(path.join(ROOT, 'i18n.js'), 'utf8'));
    dictionaries = { en:entries(slices.en), it:entries(slices.it) };
  }
  return dictionaries;
}

function escapeAttribute(text){
  return String(text).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

function plainText(html){
  return String(html).replace(/<[^>]*>/g, '').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&')
    .replace(/&#39;|&rsquo;|’/g, '\'').replace(/\s+/g, ' ').trim();
}

// Where the element whose open tag ends at `from` closes: same-name tags are
// counted, so a nested <div> or <span> does not end it early.
function closingIndex(html, tagName, from){
  const pattern = new RegExp(`<(/?)${tagName}\\b[^>]*>`, 'gi');
  pattern.lastIndex = from;
  let depth = 1;
  let match;
  while((match = pattern.exec(html))){
    if(match[0].endsWith('/>')) continue;
    depth += match[1] ? -1 : 1;
    if(depth === 0) return match.index;
  }
  throw new Error(`Unclosed <${tagName}> after offset ${from}`);
}

// Replaces the content of every element whose open tag matches `openPattern`
// (which must capture the tag name as group 1) with what `fill` returns.
function replaceContents(html, openPattern, fill){
  let output = '';
  let cursor = 0;
  openPattern.lastIndex = 0;
  let match;
  while((match = openPattern.exec(html))){
    const tagName = match[1];
    const start = match.index + match[0].length;
    const end = closingIndex(html, tagName, start);
    const replacement = fill(match[0], html.slice(start, end));
    if(replacement === null) continue;
    output += html.slice(cursor, start) + replacement;
    cursor = end;
    openPattern.lastIndex = end;
  }
  return output + html.slice(cursor);
}

function attribute(tag, name){
  const match = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return match ? match[1] : null;
}

function setAttribute(tag, name, value){
  const written = `${name}="${escapeAttribute(value)}"`;
  return new RegExp(`\\s${name}="[^"]*"`).test(tag)
    ? tag.replace(new RegExp(`\\s${name}="[^"]*"`), ` ${written}`)
    : tag.replace(/\s*\/?>$/, ending => ` ${written}${ending}`);
}

function translateKeys(html){
  const { en, it } = italian();
  const missing = new Set();
  const say = key => {
    if(!it.has(key)){ missing.add(key); return en.get(key); }
    return it.get(key);
  };
  // Text: the element's content becomes the Italian, markup included, as
  // i18n.js applyTranslations writes it.
  html = replaceContents(html, /<([a-z][\w-]*)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>/gi, (open, inner) => {
    const key = attribute(open, 'data-i18n');
    return en.has(key) || it.has(key) ? say(key) : inner;
  });
  // Attributes.
  html = html.replace(/<[a-z][\w-]*\b[^>]*\sdata-i18n-(?:ph|title|aria-label)="[^"]*"[^>]*>/gi, tag => {
    const ph = attribute(tag, 'data-i18n-ph');
    const title = attribute(tag, 'data-i18n-title');
    const label = attribute(tag, 'data-i18n-aria-label');
    if(ph) tag = setAttribute(tag, 'placeholder', say(ph));
    if(title) tag = setAttribute(tag, 'title', say(title));
    if(label) tag = setAttribute(tag, 'aria-label', say(label));
    return tag;
  });
  if(missing.size) throw new Error(`No Italian for ${[...missing].join(', ')}`);
  return html;
}

// The footer has no keys: i18n.js translateFooter matches its English text.
function translateFooter(html){
  const { en, it } = italian();
  const byText = new Map();
  for(const [key, value] of en) if(key.startsWith('footer.') && it.has(key)) byText.set(plainText(value), it.get(key));
  return replaceContents(html, /<(footer)\b[^>]*class="[^"]*\bsite-footer\b[^"]*"[^>]*>/gi, (open, inner) =>
    inner
      .replace(/(<(?:a|button|p|span|div)\b[^>]*>)([^<]+)(<\/(?:a|button|p|span|div)>)/g, (whole, start, text, end) => {
        const italianText = byText.get(plainText(text));
        return italianText ? `${start}${italianText}${end}` : whole;
      })
      .replace(/(<(?:a|button)\b[^>]*\saria-label=")([^"]+)(")/g, (whole, start, label, end) => {
        const italianText = byText.get(plainText(label));
        return italianText ? `${start}${escapeAttribute(italianText)}${end}` : whole;
      }));
}

// Wording the page's scripts translate as it runs (a filter option, a label
// with no key): visible text that is exactly an English sentence of i18n.js or
// i18n-phrases-it.js, where that sentence has one Italian, gets it here too.
let sentences = null;
function italianSentences(){
  if(sentences) return sentences;
  const { en, it } = italian();
  const candidates = new Map();
  const offer = (english, italianText) => {
    const key = plainText(english);
    if(!key || !/[A-Za-z]{2}/.test(key) || /[{<]/.test(english) || /[{<]/.test(italianText)) return;
    if(!candidates.has(key)) candidates.set(key, new Set());
    candidates.get(key).add(italianText);
  };
  for(const [key, value] of en) if(it.has(key)) offer(value, it.get(key));
  const context = { window:{} };
  vm.createContext(context);
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'i18n-phrases-it.js'), 'utf8'), context);
  for(const [english, italianText] of Object.entries(context.window.ORMA_PHRASES_IT || {})) offer(english, italianText);
  sentences = new Map([...candidates].filter(([, options]) => options.size === 1).map(([english, options]) => [english, [...options][0]]));
  return sentences;
}

function translateLeftoverText(html){
  const table = italianSentences();
  return html.replace(/>([^<>]+)</g, (whole, text) => {
    const italianText = table.get(plainText(text));
    if(!italianText || plainText(text) === plainText(italianText)) return whole;
    const lead = text.match(/^\s*/)[0];
    const trail = text.match(/\s*$/)[0];
    return `>${lead}${italianText.replace(/&(?![a-z#\d]+;)/gi, '&amp;')}${trail}<`;
  });
}

// The crawlable list of every walk on the browse page: Italian names and the
// Italian walk pages (its region headings are phrases, translated with the rest).
function italianTrailIndex(html, italianNames){
  const START = '<!-- TRAIL-INDEX-START';
  const END = '<!-- TRAIL-INDEX-END -->';
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if(a < 0 || b < 0) return html;
  const block = html.slice(a, b)
    .replace(/<a href="trail\.html\?id=([^"]+)"([^>]*)>([^<]*)<\/a>/g, (whole, slug, rest, name) => {
      const italianName = italianNames && italianNames.get(decodeURIComponent(slug));
      return `<a href="/it/trails/${slug}.html"${rest}>${italianName ? escapeAttribute(italianName).replace(/&quot;/g, '"') : name}</a>`;
    });
  return html.slice(0, a) + block + html.slice(b);
}

// A page written in both languages keeps only its Italian.
function keepItalianBlocks(html){
  html = replaceContents(html, /<([a-z][\w-]*)\b[^>]*\sdata-lang-block="en"[^>]*>/gi, () => '');
  html = html.replace(/<([a-z][\w-]*)\b[^>]*\sdata-lang-block="en"[^>]*><\/\1>\s*/gi, '');
  return html.replace(/(<[a-z][\w-]*\b[^>]*\sdata-lang-block="it")\s+hidden(?=[\s>])/gi, '$1');
}

function localAddress(value){
  return !/^(?:[a-z][\w+.-]*:|\/\/|#|\?|\{|\$)/i.test(value) && value !== '';
}

function italianLink(value){
  const [address, rest = ''] = value.split(/(?=[?#])/);
  for(const [pattern, replacement] of ITALIAN_LINKS){
    if(pattern.test(address)) return address.replace(pattern, replacement) + rest;
  }
  return null;
}

// Links to a page with an Italian copy go to the copy; every other written
// address becomes a root path; an in-page anchor stays on this copy.
function rewriteAddresses(html, italianUrl){
  return html.replace(/(\s(?:href|src|action|poster)=")([^"]*)(")/g, (whole, start, value, end) => {
    if(/^#/.test(value)) return `${start}${italianUrl}${value}${end}`;
    if(/^\/(?!\/)/.test(value)){
      const copy = italianLink(value);
      return copy ? `${start}${copy}${end}` : whole;
    }
    if(!localAddress(value)) return whole;
    const copy = italianLink(value);
    return `${start}${copy || `/${value.replace(/^\.\//, '')}`}${end}`;
  }).replace(/(\ssrcset=")([^"]*)(")/g, (whole, start, value, end) =>
    start + value.split(',').map(part => part.replace(/^(\s*)(\S+)/, (all, space, address) =>
      localAddress(address) ? `${space}/${address}` : all)).join(',') + end);
}

// Markup only: an address or a data-i18n inside a <script> or <style> is code,
// which the page runs as it is (its addresses resolve through <base>).
function outsideCode(html, transform){
  const parts = html.split(/(<(script|style)\b[^>]*>[\s\S]*?<\/\2>)/i);
  let output = '';
  for(let index = 0; index < parts.length; index += 3){
    output += transform(parts[index]);
    if(index + 1 < parts.length) output += parts[index + 1];
  }
  return output;
}

function head(html, page, meta){
  const englishUrl = `${BASE_URL}${meta.url}`;
  const italianUrl = `${BASE_URL}${meta.italianUrl}`;
  const links =
    `<base href="/">\n` +
    `<link rel="canonical" href="${italianUrl}">\n` +
    `<link rel="alternate" hreflang="en" href="${englishUrl}">\n` +
    `<link rel="alternate" hreflang="it" href="${italianUrl}">\n` +
    `<link rel="alternate" hreflang="x-default" href="${englishUrl}">`;
  html = html
    .replace(/<html lang="en"[^>]*>/, '<html lang="it" data-orma-lang="it">')
    .replace(/<title>[^<]*<\/title>/, `<title>${escapeAttribute(meta.title)}</title>`)
    .replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${escapeAttribute(meta.description)}">`)
    .replace(/\s*<link rel="canonical"[^>]*>/, '')
    .replace(/\s*<link rel="alternate" hreflang="[^"]*"[^>]*>/g, '')
    .replace(/(<meta property="og:locale" content=")[^"]*(")/, '$1it_IT$2')
    .replace(/(<meta property="og:title" content=")[^"]*(")/, `$1${escapeAttribute(meta.title)}$2`)
    .replace(/(<meta property="og:description" content=")[^"]*(")/, `$1${escapeAttribute(meta.description)}$2`)
    .replace(/(<meta property="og:url" content=")[^"]*(")/, `$1${italianUrl}$2`);
  // <base> must come before any address in <head>.
  return html.replace(/(<meta charset="[^"]*">)/i, `$1\n${links}`);
}

function italianCopy(englishHtml, page, options = {}){
  const meta = PAGES[page];
  if(!meta) throw new Error(`No Italian copy is defined for ${page}`);
  let html = englishHtml;
  html = keepItalianBlocks(html);
  html = italianTrailIndex(html, options.italianNames);
  html = outsideCode(html, part =>
    rewriteAddresses(translateLeftoverText(translateFooter(translateKeys(part))), meta.italianUrl));
  html = head(html, page, meta);
  return html;
}

function writeItalianMainPages(root = ROOT, options = {}){
  fs.mkdirSync(path.join(root, 'it'), { recursive:true });
  return Object.keys(PAGES).map(page => {
    const english = fs.readFileSync(path.join(root, page), 'utf8');
    fs.writeFileSync(path.join(root, 'it', page), italianCopy(english, page, options), 'utf8');
    return `it/${page}`;
  });
}

