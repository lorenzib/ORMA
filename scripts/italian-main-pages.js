// keeps every address the page or its scripts build resolving from the site
// root, as on the English page; written addresses become root paths too, so the
// asset stamper (scripts/build-pages-site.js) keys them. Generated by
// scripts/generate-trail-pages.js after the browse index; do not edit it/*.html
// for these pages by hand.

