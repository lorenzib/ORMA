#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const packagesDir = path.join(root, 'offline', 'packages');
const trails = {};

if(fs.existsSync(packagesDir)){
  fs.readdirSync(packagesDir, { withFileTypes:true })
    .filter(entry => entry.isDirectory() && /^[a-z0-9-]+$/.test(entry.name))
    .sort((a, b) => a.name.localeCompare(b.name))
    .forEach(entry => {
      const graphPath = path.join(packagesDir, entry.name, 'footpath-network.json');
      if(!fs.existsSync(graphPath)) return;
      const graph = JSON.parse(fs.readFileSync(graphPath, 'utf8'));
      if(graph.schemaVersion !== 1 || graph.trailId !== entry.name ||
         !Array.isArray(graph.nodes) || !Array.isArray(graph.edges) ||
         !Array.isArray(graph.trailNodes) || !graph.trailNodes.length){
        throw new Error(`Invalid footpath routing graph for ${entry.name}`);
      }
      trails[entry.name] = {
        graphUrl:`offline/packages/${entry.name}/footpath-network.json`,
        source:'OpenStreetMap',
        networkStatus:'mapped',
        bounds:graph.bounds,
        nodeCount:graph.nodes.length,
        edgeCount:graph.edges.length,
      };
    });
}

const coverage = {
  schemaVersion:1,
  maxWalkingRouteM:5000,
  trails,
};
const output = `// Generated by scripts/build-trail-routing-coverage.js. Do not edit.\n` +
  `window.DoloPawsTrailRoutingCoverage=Object.freeze(${JSON.stringify(coverage)});\n`;
fs.writeFileSync(path.join(root, 'trail-routing-coverage.js'), output);
console.log(`Published mapped walking-route coverage for ${Object.keys(trails).length} trails.`);
