'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { applyVerifiedTrailOverrides } = require('./verified-trail-overrides');
const { applyTrailImageOverrides } = require('./trail-image-overrides');
const { applyTrailGalleryPhotos } = require('./trail-gallery-photos');
const { applyRouteNumberEvidence } = require('./route-number-evidence');
const { applyLiftAccess } = require('./lift-access');
const { applyTrailSeasons } = require('./trail-seasons');
const { applyLiftSeasons } = require('./lift-seasons');
const { applyDogSeasons } = require('./dog-seasons');
const { loadSlugOverrides, applyTrailNameOverrides } = require('./trail-slug-overrides');

const DEFAULT_FILES = [
  'trails-data.js',
  'osm-trails-data.js',
  'osm-trails-savoy-data.js',
  'board-trails-data.js',
  'trail-audits.js',
  'regions-config.js',
];

function loadProductionTrails(root, files = DEFAULT_FILES, options = {}){
  const source = files
    .map(file => fs.readFileSync(path.join(root, file), 'utf8'))
    .join('\n;\n');
  let trails = null;
  const sandbox = {
    window: {},
    console,
    __capture(value){ trails = value; },
  };
  vm.runInNewContext(
    `${source}\n;window.DoloPawsRegions.assign(trails); __capture(trails);`,
    sandbox,
    { filename: 'production-trail-data-bundle.js' }
  );
  if(!Array.isArray(trails) || !trails.length){
    throw new Error('Production trail sources did not produce a non-empty trail array.');
  }
  const overridePath = path.join(root, 'data', 'verified-trail-overrides.json');
  const overrides = fs.existsSync(overridePath) ? JSON.parse(fs.readFileSync(overridePath, 'utf8')) : { trails:[] };
  const imageOverridePath=path.join(root,'data','trail-image-overrides.json');
  const imageOverrides=fs.existsSync(imageOverridePath)?JSON.parse(fs.readFileSync(imageOverridePath,'utf8')):{trails:[]};
  const galleryPath=path.join(root,'data','trail-gallery-photos.json');
  const gallery=fs.existsSync(galleryPath)?JSON.parse(fs.readFileSync(galleryPath,'utf8')):{trails:[]};
  // The verification campaign ranks candidates from these objects, and the gate
  // it ranks them towards asks for supported authoritative route guidance. Until
  // now this status was derived only when the site data was generated, so the
  // campaign could not see it: 3 of 165 trails carried the field, and the queue
  // filled with routes that cannot produce route guidance at all.
  const liftPath = path.join(root, 'data', 'lift-access.json');
  const liftAccess = fs.existsSync(liftPath) ? JSON.parse(fs.readFileSync(liftPath, 'utf8')) : { trails:[] };
  // When in the year each walk is a walk, written by npm run build:trail-seasons.
  const seasonsPath = path.join(root, 'data', 'trail-seasons.json');
  // The seasons builder reads the trails without them: a walk it dropped would
  // otherwise stop it before it could write the file that drops it.
  const seasons = options.seasons !== false && fs.existsSync(seasonsPath) ? JSON.parse(fs.readFileSync(seasonsPath, 'utf8')) : { trails:{} };
  // When the lifts the walks ride are running, curated in data/lift-seasons.json.
  const liftSeasonsPath = path.join(root, 'data', 'lift-seasons.json');
  const liftSeasons = options.seasons !== false && fs.existsSync(liftSeasonsPath) ? JSON.parse(fs.readFileSync(liftSeasonsPath, 'utf8')) : { lifts:{}, trails:{} };
  // Seasonal risks to dogs (caterpillars, ticks, cows), curated in data/dog-seasons.json.
  const dogSeasonsPath = path.join(root, 'data', 'dog-seasons.json');
  const dogSeasons = options.seasons !== false && fs.existsSync(dogSeasonsPath) ? JSON.parse(fs.readFileSync(dogSeasonsPath, 'utf8')) : { risks:{} };
  // Last, so the name a reader sees is the published one whatever the importer
  // called it. The files carrying the imported name are regenerated by the
  // promoter, so this is an override for the same reason the image, lift and
  // route-number facts are.
  return applyTrailNameOverrides(
    applyRouteNumberEvidence(
      applyDogSeasons(applyLiftSeasons(applyTrailSeasons(applyLiftAccess(applyTrailGalleryPhotos(applyTrailImageOverrides(applyVerifiedTrailOverrides(trails, overrides), imageOverrides), gallery), liftAccess), seasons), liftSeasons), dogSeasons),
      root,
    ),
    loadSlugOverrides(root),
  );
}

module.exports = {
  DEFAULT_FILES,
  loadProductionTrails,
};
